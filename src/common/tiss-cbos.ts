const TISS_CBOS_BY_CODE = new Map(TISS_CBOS.map((item) => [item.code, item]));

export function isTissCbosCode(code: string): boolean {
  return TISS_CBOS_BY_CODE.has(code);
}

export function findTissCbos(code: string): TissCbos | undefined {
  return TISS_CBOS_BY_CODE.get(code);
}

export function searchTissCbos(query: string, limit = 30): TissCbos[] {
  const term = query.trim().toLocaleLowerCase('pt-BR');
  const digits = term.replace(/\D/g, '');
  const matches = TISS_CBOS.filter((item) => {
    if (!term) return true;
    if (digits && item.code.includes(digits)) return true;
    return item.name.toLocaleLowerCase('pt-BR').includes(term);
  });
  return [...matches]
    .sort(
      (left, right) =>
        left.name.localeCompare(right.name, 'pt-BR') ||
        left.code.localeCompare(right.code),
    )
    .slice(0, limit);
}
